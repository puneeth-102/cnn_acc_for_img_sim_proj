`timescale 1ns/1ps

module tb_cnn_top;

    // --------------------------------------------------
    // Parameters
    // --------------------------------------------------

    parameter IMAGE_SIZE  = 16;
    parameter NUM_FILTERS = 4;

    parameter DATA_WIDTH  = 32;
    parameter FEATURE_W   = 8;
    parameter EMBEDDING_W = 32;


    // --------------------------------------------------
    // Clock and reset
    // --------------------------------------------------

    logic clk;
    logic rst;
    logic start;


    // --------------------------------------------------
    // Input image
    // --------------------------------------------------

    logic signed [7:0] image [0:255];


    // --------------------------------------------------
    // Convolution weights
    // 4 filters × 9 weights
    // --------------------------------------------------

    logic signed [7:0] conv_weights [0:35];


    // --------------------------------------------------
    // FC weights
    // 16 × 196
    // --------------------------------------------------

    logic signed [FEATURE_W-1:0]
        fc_weights [0:15][0:195];


    // --------------------------------------------------
    // FC biases
    // --------------------------------------------------

    logic signed [EMBEDDING_W-1:0]
        fc_bias [0:15];


    // --------------------------------------------------
    // CNN output
    // --------------------------------------------------

    logic signed [EMBEDDING_W-1:0]
        embedding [0:15];

    logic busy;
    logic done;


    integer i;
    integer j;


    // ==================================================
    // DUT
    // ==================================================

    cnn_top #(
        .IMAGE_SIZE  (IMAGE_SIZE),
        .NUM_FILTERS (NUM_FILTERS),
        .DATA_WIDTH  (DATA_WIDTH),
        .FEATURE_W   (FEATURE_W),
        .EMBEDDING_W (EMBEDDING_W)
    ) dut (

        .clk          (clk),
        .rst          (rst),
        .start        (start),

        .image        (image),
        .conv_weights (conv_weights),

        .fc_weights   (fc_weights),
        .fc_bias      (fc_bias),

        .embedding    (embedding),

        .busy         (busy),
        .done         (done)
    );


    // ==================================================
    // CLOCK
    // ==================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // ==================================================
    // TEST
    // ==================================================

    initial begin

        // ----------------------------------------------
        // INITIAL VALUES
        // ----------------------------------------------

        rst   = 1'b1;
        start = 1'b0;


        // ----------------------------------------------
        // Initialize image
        // ----------------------------------------------

        for (i = 0; i < 256; i = i + 1)
            image[i] = 8'sd1;


        // ----------------------------------------------
        // Initialize convolution weights
        //
        // All weights = 1
        // ----------------------------------------------

        for (i = 0; i < 36; i = i + 1)
            conv_weights[i] = 8'sd1;


        // ----------------------------------------------
        // Initialize FC weights
        //
        // All weights = 1
        // ----------------------------------------------

        for (j = 0; j < 16; j = j + 1)

            for (i = 0; i < 196; i = i + 1)

                fc_weights[j][i] = 8'sd1;


        // ----------------------------------------------
        // Initialize FC biases
        // ----------------------------------------------

        for (j = 0; j < 16; j = j + 1)
            fc_bias[j] = 32'sd0;


        // ----------------------------------------------
        // Hold reset
        // ----------------------------------------------

        #20;

        rst = 1'b0;

        #20;


        // ----------------------------------------------
        // Start CNN
        // ----------------------------------------------

        $display("----------------------------------------");
        $display("Starting CNN...");
        $display("----------------------------------------");

        start = 1'b1;

        #10;

        start = 1'b0;


        // ----------------------------------------------
        // Wait for completion
        // ----------------------------------------------

        wait(done == 1'b1);


        // ----------------------------------------------
        // Display embedding
        // ----------------------------------------------

        $display("----------------------------------------");
        $display("CNN COMPLETED");
        $display("----------------------------------------");

        for (j = 0; j < 16; j = j + 1) begin

            $display(
                "Embedding[%0d] = %0d",
                j,
                embedding[j]
            );

        end


        $display("----------------------------------------");

        #20;

        $finish;

    end


    // ==================================================
    // TIMEOUT PROTECTION
    // ==================================================

    initial begin

        #1000000;

        $display("----------------------------------------");
        $display("ERROR: CNN simulation timeout");
        $display("----------------------------------------");

        $finish;

    end

endmodule